"""Generate settings TypeScript and Electron exposure lists from Python DTOs.

Only the wire DTO subset is supported; unsupported annotations fail loudly.
--check compares outputs without writing files or building the UI.
"""

import argparse
import ast
import json
from pathlib import Path

from watched_kettle import settings_protocol as protocol

ROOT = Path(__file__).resolve().parents[1]
NOTICE = "Generated by scripts/generate_settings_protocol.py; do not edit."


def ts_type(node):
    if isinstance(node, ast.Name):
        return {
            "str": "string",
            "int": "number",
            "float": "number",
            "bool": "boolean",
            "object": "unknown",
        }.get(node.id, node.id)
    if isinstance(node, ast.Constant):
        if isinstance(node.value, str):
            return node.value  # forward reference, e.g. JsonValue
        if node.value is None:
            return "null"
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr):

        def members(value):
            if isinstance(value, ast.BinOp) and isinstance(value.op, ast.BitOr):
                return members(value.left) + members(value.right)
            return [ts_type(value)]

        return " | ".join(dict.fromkeys(members(node)))
    if isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name):
        name = node.value.id
        args = node.slice.elts if isinstance(node.slice, ast.Tuple) else [node.slice]
        if name == "NotRequired":
            return ts_type(args[0])
        if name == "Literal":
            return " | ".join(json.dumps(ast.literal_eval(a)) for a in args)
        if name == "list":
            return f"Array<{ts_type(args[0])}>"
        if name == "dict":
            return f"{{ [key: {ts_type(args[0])}]: {ts_type(args[1])} }}"
        if name == "tuple":
            return "[" + ", ".join(ts_type(a) for a in args) + "]"
    raise ValueError(f"Unsupported protocol type: {ast.unparse(node)}")


def outputs():
    source = ROOT / "watched_kettle/settings_protocol.py"
    lines = [f"// {NOTICE}"]
    for node in ast.parse(source.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            if isinstance(node.value, (ast.BinOp, ast.Subscript)):
                lines.append(
                    f"export type {node.targets[0].id} = {ts_type(node.value)};"
                )
        if not isinstance(node, ast.ClassDef) or node.name == "Command":
            continue
        if node.name == "Empty":
            lines.append("export type Empty = { [key: string]: never };")
            continue
        bases = [ast.unparse(b) for b in node.bases if ast.unparse(b) != "TypedDict"]
        optional = any(
            k.arg == "total"
            and isinstance(k.value, ast.Constant)
            and k.value.value is False
            for k in node.keywords
        )
        fields = []
        for field in node.body:
            if not isinstance(field, ast.AnnAssign):
                continue
            if not isinstance(field.target, ast.Name):
                raise ValueError("Protocol fields must have simple names")
            opt = optional or (
                isinstance(field.annotation, ast.Subscript)
                and isinstance(field.annotation.value, ast.Name)
                and field.annotation.value.id == "NotRequired"
            )
            fields.append(
                f"  {field.target.id}{'?' if opt else ''}: {ts_type(field.annotation)};"
            )
        prefix = " & ".join(bases) + " & " if bases else ""
        lines.append(
            f"export type {node.name} = {prefix}{{\n" + "\n".join(fields) + "\n};"
        )
    lines.append("export interface CommandMap {")
    for name, command in protocol.COMMANDS.items():
        lines.append(
            f'  "{name}": {{ args: {command.request}; result: {command.response} }};'
        )
    lines.append("}")
    public = [
        name for name, cmd in protocol.COMMANDS.items() if cmd.caller == "renderer"
    ]
    assistant = [
        name for name in public if protocol.COMMANDS[name].edition == "pet-assistant"
    ]
    lines.append(
        "export type RendererCommand = "
        + " | ".join(json.dumps(n) for n in public)
        + ";"
    )
    lines.extend(
        [
            "export type Args<M extends RendererCommand> = CommandMap[M]['args'];",
            "export type Result<M extends RendererCommand> = CommandMap[M]['result'];",
            "export type Request = <M extends RendererCommand>(method: M, ...args: {} extends Args<M> ? [args?: Args<M>] : [args: Args<M>]) => Promise<Result<M>>;",
            "export type FileResult<P extends 'pet' | 'import' | 'export'> = Cancelled | (P extends 'pet' ? PetPreparation : P extends 'import' ? ElementImported : Saved);",
            "export type FileRequest = <P extends 'pet' | 'import' | 'export'>(purpose: P, ...args: P extends 'import' ? [kind: ElementKind] : []) => Promise<FileResult<P>>;",
        ]
    )
    exposed = {"renderer": public, "assistant": assistant}
    return {
        ROOT / "settings-ui/src/protocol.generated.ts": "\n\n".join(lines) + "\n",
        ROOT
        / "settings-ui/electron/commands.generated.cjs": f"// {NOTICE}\nmodule.exports = "
        + json.dumps(exposed, indent=2)
        + ";\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding="utf-8")
    if stale:
        raise SystemExit("Settings protocol outputs are stale: " + ", ".join(stale))


if __name__ == "__main__":
    main()
