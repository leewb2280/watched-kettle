"""Generate the settings-window CSS and Qt constants from design/tokens.json.

Run without arguments to rewrite the generated files, or with --check to fail
when they no longer match the token source.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design" / "tokens.json"
CSS_OUTPUT = ROOT / "settings-ui" / "src" / "tokens.css"
PYTHON_OUTPUT = ROOT / "watched_kettle" / "ui" / "design_tokens.py"
NOTICE = "Generated by scripts/generate_design_tokens.py from design/tokens.json; do not edit."


def load_tokens(path=SOURCE):
    tokens = json.loads(path.read_text(encoding="utf-8"))
    if tokens.get("schemaVersion") != 1:
        raise ValueError("unsupported design token schema")
    themes = tokens["themes"]
    if set(themes) != {"light", "dark"} or set(themes["light"]) != set(themes["dark"]):
        raise ValueError("light and dark themes must define the same tokens")
    for alias, target in tokens.get("aliases", {}).items():
        if target not in themes["light"] or alias in themes["light"]:
            raise ValueError(f"invalid alias: {alias}")
    return tokens


def _rgb_triple(value):
    value = value.lstrip("#")
    return ", ".join(str(int(value[index : index + 2], 16)) for index in (0, 2, 4))


def _css_block(selector, theme, aliases):
    lines = [f"{selector} {{"]
    for name, value in theme.items():
        # The frame is mixed with the user's opacity in rgba(var(--frame), …).
        lines.append(f"  --{name}: {_rgb_triple(value) if name == 'frame' else value};")
    for alias, target in aliases.items():
        lines.append(f"  --{alias}: var(--{target});")
    lines.append("}")
    return lines


def render_css(tokens):
    font = tokens["font"]
    families = ", ".join(
        family if family == "sans-serif" else f'"{family}"' for family in font["family"]
    )
    aliases = tokens.get("aliases", {})
    lines = [f"/* {NOTICE} */", ":root {", f"  --font-family: {families};"]
    lines += [f"  --font-{name}: {size}px;" for name, size in font["size"].items()]
    lines += [
        f"  --weight-{name}: {weight};" for name, weight in font["weight"].items()
    ]
    lines += [
        f"  --radius-{name}: {value}px;" for name, value in tokens["radius"].items()
    ]
    lines.append("}")
    lines += _css_block(":root", tokens["themes"]["light"], aliases)
    lines += _css_block(':root[data-theme="dark"]', tokens["themes"]["dark"], aliases)
    return "\n".join(lines) + "\n"


def _literal(value):
    # Double-quoted literals keep the generated module stable under ruff format.
    return json.dumps(value, ensure_ascii=False)


def _python_dict(name, values):
    lines = [f"{name} = {{"]
    lines += [
        f"    {_literal(key)}: {_literal(value)}," for key, value in values.items()
    ]
    lines.append("}")
    return lines


def render_python(tokens):
    font = tokens["font"]
    lines = [f'"""{NOTICE}"""', ""]
    families = ", ".join(_literal(family) for family in font["family"])
    lines.append(f"FONT_FAMILIES = ({families})")
    lines += _python_dict("FONT_SIZES", font["size"])
    lines += _python_dict("FONT_WEIGHTS", font["weight"])
    lines += _python_dict("RADIUS", tokens["radius"])
    for theme in ("light", "dark"):
        values = dict(tokens["themes"][theme])
        values.update(
            (alias, values[target]) for alias, target in tokens["aliases"].items()
        )
        lines += _python_dict(f"{theme.upper()}_THEME", values)
    lines += [
        'THEMES = {"light": LIGHT_THEME, "dark": DARK_THEME}',
        "",
        "",
        "def theme_tokens(name):",
        '    """Return a theme\'s colors; unknown names use the light theme."""',
        "    return THEMES.get(name, LIGHT_THEME)",
    ]
    return "\n".join(lines) + "\n"


def outputs(tokens):
    return {CSS_OUTPUT: render_css(tokens), PYTHON_OUTPUT: render_python(tokens)}


def main(arguments=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(arguments)
    stale = []
    for path, content in outputs(load_tokens()).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_bytes(content.encode("utf-8"))
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("Design token outputs are stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
